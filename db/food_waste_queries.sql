
BEGIN;

CREATE SCHEMA IF NOT EXISTS food_waste;

-- 1. Create tables

CREATE TABLE IF NOT EXISTS food_waste.country (
    m49_code VARCHAR(3) PRIMARY KEY,
    country_name VARCHAR(150) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS food_waste.commodity (
    cpc_code VARCHAR(30) PRIMARY KEY,
    commodity_name VARCHAR(250) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS food_waste.method (
    method_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    method_name VARCHAR(250) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS food_waste.activity (
    activity_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_name VARCHAR(250) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS food_waste.source (
    source_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference TEXT,
    url TEXT
);

CREATE TABLE IF NOT EXISTS food_waste.observation (
    record_id INTEGER PRIMARY KEY,
    year INTEGER NOT NULL,
    loss_percentage NUMERIC(8,3) NOT NULL,
    cpc_code VARCHAR(30) NOT NULL,
    method_id INTEGER,
    m49_code VARCHAR(3) NOT NULL,
    source_id INTEGER NOT NULL,

    FOREIGN KEY (cpc_code)
        REFERENCES food_waste.commodity(cpc_code),

    FOREIGN KEY (method_id)
        REFERENCES food_waste.method(method_id),

    FOREIGN KEY (m49_code)
        REFERENCES food_waste.country(m49_code),

    FOREIGN KEY (source_id)
        REFERENCES food_waste.source(source_id),

    CHECK (loss_percentage >= 0 AND loss_percentage <= 100)
);

CREATE TABLE IF NOT EXISTS food_waste.observation_activity (
    record_id INTEGER NOT NULL,
    activity_id INTEGER NOT NULL,

    PRIMARY KEY (record_id, activity_id),

    FOREIGN KEY (record_id)
        REFERENCES food_waste.observation(record_id)
        ON DELETE CASCADE,

    FOREIGN KEY (activity_id)
        REFERENCES food_waste.activity(activity_id)
);

-- Staging tables for CSV imports

CREATE TABLE IF NOT EXISTS food_waste.stg_food_waste (
    m49_code TEXT,
    country TEXT,
    cpc_code TEXT,
    commodity TEXT,
    year TEXT,
    loss_percentage TEXT,
    activity TEXT,
    method_data_collection TEXT,
    reference TEXT,
    url TEXT,
    record_id TEXT,
    activity_count TEXT
);

CREATE TABLE IF NOT EXISTS food_waste.stg_activity_long (
    record_id TEXT,
    activity TEXT
);

-- 2. Load country, commodity, method and activity

INSERT INTO food_waste.country (m49_code, country_name)
SELECT DISTINCT
    TRIM(m49_code),
    TRIM(country)
FROM food_waste.stg_food_waste
WHERE TRIM(m49_code) <> ''
  AND TRIM(country) <> ''
ON CONFLICT (m49_code)
DO UPDATE SET country_name = EXCLUDED.country_name;

INSERT INTO food_waste.commodity (cpc_code, commodity_name)
SELECT DISTINCT
    TRIM(cpc_code),
    TRIM(commodity)
FROM food_waste.stg_food_waste
WHERE TRIM(cpc_code) <> ''
  AND TRIM(commodity) <> ''
ON CONFLICT (cpc_code)
DO UPDATE SET commodity_name = EXCLUDED.commodity_name;

INSERT INTO food_waste.method (method_name)
SELECT DISTINCT TRIM(method_data_collection)
FROM food_waste.stg_food_waste
WHERE TRIM(method_data_collection) <> ''
ON CONFLICT (method_name) DO NOTHING;

INSERT INTO food_waste.activity (activity_name)
SELECT DISTINCT TRIM(activity)
FROM food_waste.stg_activity_long
WHERE TRIM(activity) <> ''
ON CONFLICT (activity_name) DO NOTHING;

-- 3. Load sources

INSERT INTO food_waste.source (reference, url)
SELECT DISTINCT
    NULLIF(TRIM(s.reference), ''),
    NULLIF(TRIM(s.url), '')
FROM food_waste.stg_food_waste s
WHERE NOT EXISTS (
    SELECT 1
    FROM food_waste.source src
    WHERE src.reference IS NOT DISTINCT FROM NULLIF(TRIM(s.reference), '')
      AND src.url IS NOT DISTINCT FROM NULLIF(TRIM(s.url), '')
);

-- 4. Load observations

INSERT INTO food_waste.observation (
    record_id,
    year,
    loss_percentage,
    cpc_code,
    method_id,
    m49_code,
    source_id
)
SELECT
    s.record_id::INTEGER,
    s.year::INTEGER,
    s.loss_percentage::NUMERIC(8,3),
    TRIM(s.cpc_code),
    m.method_id,
    TRIM(s.m49_code),
    src.source_id
FROM food_waste.stg_food_waste s

JOIN food_waste.country c
    ON c.m49_code = TRIM(s.m49_code)

JOIN food_waste.commodity cm
    ON cm.cpc_code = TRIM(s.cpc_code)

LEFT JOIN food_waste.method m
    ON m.method_name = NULLIF(TRIM(s.method_data_collection), '')

JOIN food_waste.source src
    ON src.reference IS NOT DISTINCT FROM NULLIF(TRIM(s.reference), '')
   AND src.url IS NOT DISTINCT FROM NULLIF(TRIM(s.url), '')

WHERE TRIM(s.record_id) <> ''
  AND TRIM(s.year) <> ''
  AND TRIM(s.loss_percentage) <> ''

ON CONFLICT (record_id)
DO UPDATE SET
    year = EXCLUDED.year,
    loss_percentage = EXCLUDED.loss_percentage,
    cpc_code = EXCLUDED.cpc_code,
    method_id = EXCLUDED.method_id,
    m49_code = EXCLUDED.m49_code,
    source_id = EXCLUDED.source_id;

-- 5. Load observation activities

INSERT INTO food_waste.observation_activity (
    record_id,
    activity_id
)
SELECT DISTINCT
    al.record_id::INTEGER,
    a.activity_id
FROM food_waste.stg_activity_long al

JOIN food_waste.activity a
    ON a.activity_name = TRIM(al.activity)

JOIN food_waste.observation o
    ON o.record_id = al.record_id::INTEGER

WHERE TRIM(al.record_id) <> ''
  AND TRIM(al.activity) <> ''

ON CONFLICT (record_id, activity_id) DO NOTHING;

COMMIT;

-- 6. Check table row counts

SELECT 'country' AS table_name, COUNT(*) AS row_count
FROM food_waste.country

UNION ALL
SELECT 'commodity', COUNT(*) FROM food_waste.commodity

UNION ALL
SELECT 'method', COUNT(*) FROM food_waste.method

UNION ALL
SELECT 'activity', COUNT(*) FROM food_waste.activity

UNION ALL
SELECT 'source', COUNT(*) FROM food_waste.source

UNION ALL
SELECT 'observation', COUNT(*) FROM food_waste.observation

UNION ALL
SELECT 'observation_activity', COUNT(*)
FROM food_waste.observation_activity

ORDER BY table_name;

-- 7. Check foreign key relationships

SELECT
    (SELECT COUNT(*)
     FROM food_waste.observation o
     LEFT JOIN food_waste.country c
        ON c.m49_code = o.m49_code
     WHERE c.m49_code IS NULL) AS invalid_countries,

    (SELECT COUNT(*)
     FROM food_waste.observation o
     LEFT JOIN food_waste.commodity c
        ON c.cpc_code = o.cpc_code
     WHERE c.cpc_code IS NULL) AS invalid_commodities,

    (SELECT COUNT(*)
     FROM food_waste.observation o
     LEFT JOIN food_waste.source s
        ON s.source_id = o.source_id
     WHERE s.source_id IS NULL) AS invalid_sources,

    (SELECT COUNT(*)
     FROM food_waste.observation_activity oa
     LEFT JOIN food_waste.observation o
        ON o.record_id = oa.record_id
     WHERE o.record_id IS NULL) AS invalid_observations,

    (SELECT COUNT(*)
     FROM food_waste.observation_activity oa
     LEFT JOIN food_waste.activity a
        ON a.activity_id = oa.activity_id
     WHERE a.activity_id IS NULL) AS invalid_activities;
